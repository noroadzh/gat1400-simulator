// Package media 提供模拟器用的轻量媒体存储与占位图生成。
//
// 当前范围：内存 Put/Get + 最小 JPEG 占位图（base64 可嵌入资源 Data）。
// 后续可扩展为 HLS/RTSP 抽帧，而不改变调用方接口。
package media

import (
	"encoding/base64"
	"sync"
)

// Store 是进程内媒体字节存储（非持久化）。
type Store struct {
	mu   sync.RWMutex
	blob map[string][]byte
}

// NewStore 创建空媒体库。
func NewStore() *Store {
	return &Store{blob: map[string][]byte{}}
}

// Put 写入或覆盖 key 对应的原始字节。
func (s *Store) Put(key string, data []byte) {
	s.mu.Lock()
	defer s.mu.Unlock()
	cp := make([]byte, len(data))
	copy(cp, data)
	s.blob[key] = cp
}

// Get 返回拷贝后的字节；不存在时 ok=false。
func (s *Store) Get(key string) ([]byte, bool) {
	s.mu.RLock()
	defer s.mu.RUnlock()
	v, ok := s.blob[key]
	if !ok {
		return nil, false
	}
	cp := make([]byte, len(v))
	copy(cp, v)
	return cp, true
}

// Delete 移除媒体对象。
func (s *Store) Delete(key string) {
	s.mu.Lock()
	defer s.mu.Unlock()
	delete(s.blob, key)
}

